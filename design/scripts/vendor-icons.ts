// Extracts the path data of the Material Symbols Rounded glyphs the workspace uses.
// Usage: node scripts/vendor-icons.ts --from <unpacked @material-symbols/svg-400>/package
// The package is downloaded with `npm pack` into a scratch folder and is never installed.
// Each SVG must be exactly one <path> on the 0 -960 960 960 grid; anything else is rejected.
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { vendoredGlyphs } from "../src/icons/registry.ts";

const svgShape =
  /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="\d+" height="\d+" viewBox="0 -960 960 960"><path d="([MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+)"\/><\/svg>\s*$/;

export function extractPath(svg: string, file: string): string {
  const match = svgShape.exec(svg);
  if (!match) throw new Error(`${file} is not a single-path Material Symbols SVG`);
  return match[1]!;
}

function main(): void {
  const fromIndex = process.argv.indexOf("--from");
  const pkg = fromIndex > -1 ? process.argv[fromIndex + 1] : undefined;
  if (!pkg) throw new Error("Pass --from <path to the unpacked package folder>");
  const manifest = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")) as {
    name: string;
    version: string;
  };
  const entries = vendoredGlyphs().map((glyph) => {
    const read = (file: string) => readFileSync(join(pkg, "rounded", file), "utf8");
    return [
      glyph,
      {
        outline: extractPath(read(`${glyph}.svg`), `${glyph}.svg`),
        fill: extractPath(read(`${glyph}-fill.svg`), `${glyph}-fill.svg`),
      },
    ] as const;
  });
  const body = entries
    .map(
      ([glyph, p]) => `  ${glyph}: {\n    outline: "${p.outline}",\n    fill: "${p.fill}",\n  },`,
    )
    .join("\n");
  const out = new URL("../src/icons/", import.meta.url);
  writeFileSync(
    new URL("material-paths.ts", out),
    [
      `// Vendored from ${manifest.name} ${manifest.version} (Material Symbols Rounded, weight 400).`,
      "// License: Apache-2.0, see LICENSE-material-symbols.txt. Generated by scripts/vendor-icons.ts;",
      "// re-run the script instead of editing. Path data uses viewBox 0 -960 960 960.",
      "export const materialPaths: Record<string, { outline: string; fill: string }> = {",
      body,
      "};",
      "",
    ].join("\n"),
  );
  copyFileSync(join(pkg, "LICENSE"), new URL("LICENSE-material-symbols.txt", out));
  console.log(`vendor-icons: wrote ${entries.length} glyphs from ${manifest.version}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
